#!/bin/bash
export LOG_LEVEL=${LOG_LEVEL:-info}
export LEADER_SECRET=${LEADER_SECRET:-""}
export LEADER_URL=${LEADER_URL:-"https://0.0.0.0:22900"}
export ACCEPT_INSURE_CERTS=${ACCEPT_INSURE_CERTS:-true}
# Set environment variables with default values
export PERFORMANCE_ETHERNET_BROKERS="${PERFORMANCE_ETHERNET_BROKERS:-1}"
export PERFORMANCE_WIFI_BROKERS="${PERFORMANCE_WIFI_BROKERS:-1}"
export PERFORMANCE_WIFI_BROKER_BUFFER_CAPACITY="${PERFORMANCE_WIFI_BROKER_BUFFER_CAPACITY:-65535}"
export PERFORMANCE_ETHERNET_BROKER_BUFFER_CAPACITY="${PERFORMANCE_ETHERNET_BROKER_BUFFER_CAPACITY:-65535}"
export PERFORMANCE_BLUETOOTH_DEVICES_PIPELINE_SIZE="${PERFORMANCE_BLUETOOTH_DEVICES_PIPELINE_SIZE:-1024}"
export PERFORMANCE_SHARED_PROTOCOL_PROCESSORS="${PERFORMANCE_SHARED_PROTOCOL_PROCESSORS:-2}"
export PROTOCOLS_WIFI_PIPELINE_SIZE="${PROTOCOLS_WIFI_PIPELINE_SIZE:-16384}"
export PROTOCOLS_WIFI_PROCESSORS="${PROTOCOLS_WIFI_PROCESSORS:-1}"
export PROTOCOLS_TCP_PIPELINE_SIZE="${PROTOCOLS_TCP_PIPELINE_SIZE:-65535}"
export PROTOCOLS_TCP_PROCESSORS="${PROTOCOLS_TCP_PROCESSORS:-3}"
export PROTOCOLS_TCP_REASSEMBLY_BUFFER_SIZE="${PROTOCOLS_TCP_REASSEMBLY_BUFFER_SIZE:-1048576}"
export PROTOCOLS_TCP_SESSION_TIMEOUT_SECONDS="${PROTOCOLS_TCP_SESSION_TIMEOUT_SECONDS:-43200}"
export PROTOCOLS_UDP_PIPELINE_SIZE="${PROTOCOLS_UDP_PIPELINE_SIZE:-65535}"
export PROTOCOLS_UDP_PROCESSORS="${PROTOCOLS_UDP_PROCESSORS:-3}"
export PROTOCOLS_DNS_PIPELINE_SIZE="${PROTOCOLS_DNS_PIPELINE_SIZE:-4096}"
export PROTOCOLS_DNS_ENTROPY_ZSCORE_THRESHOLD="${PROTOCOLS_DNS_ENTROPY_ZSCORE_THRESHOLD:-3.0}"
export PROTOCOLS_SSH_PIPELINE_SIZE="${PROTOCOLS_SSH_PIPELINE_SIZE:-1024}"
export PROTOCOLS_SOCKS_PIPELINE_SIZE="${PROTOCOLS_SOCKS_PIPELINE_SIZE:-1024}"
export PROTOCOLS_ARP_PIPELINE_SIZE="${PROTOCOLS_ARP_PIPELINE_SIZE:-1024}"
export PROTOCOLS_DHCPV4_PIPELINE_SIZE="${PROTOCOLS_DHCPV4_PIPELINE_SIZE:-1024}"
export PROTOCOLS_UAV_REMOTE_ID_PIPELINE_SIZE="${PROTOCOLS_UAV_REMOTE_ID_PIPELINE_SIZE:-1024}"
export MISC_TRAINING_PERIOD_MINUTES="${MISC_TRAINING_PERIOD_MINUTES:-5}"
export MISC_CONTEXT_MAC_IP_RETENTION_HOURS="${MISC_CONTEXT_MAC_IP_RETENTION_HOURS:-36}"
export MISC_CONTEXT_MAC_HOSTNAME_RETENTION_HOURS="${MISC_CONTEXT_MAC_HOSTNAME_RETENTION_HOURS:-36}"


if [ -z "$LEADER_SECRET" ]; then
    echo "LEADER_SECRET environment variable is not set or empty. Exiting."
    exit 1
fi

echo "---------- Starting nzyme tap -----------"

config_file=/etc/nzyme/nzyme-tap.conf
envsubst < /etc/nzyme/nzyme-tap.conf.template > $config_file
cat /etc/nzyme/nzyme-tap-config >> $config_file

/usr/bin/nzyme-tap --configuration-file $config_file --log-level $LOG_LEVEL
